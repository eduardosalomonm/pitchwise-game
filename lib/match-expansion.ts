// Authored contacts, not generated movement: the receiver/scorer reaches the ball.
type Contact = [string, number, number];
function c(
  label: string,
  feedback: string,
  result: Ending | 'next',
  contact: Contact,
  moves: Placement[] = [],
  art?: string,
  via: [number, number][] = [],
  looseAt?: [number, number],
  routes?: Action['routes'],
): Action {
  const [player, x, y] = contact;
  const goal = result === 'goal' || result === 'concede';
  const path: [number, number][] = [
    ...via,
    [x, y],
    ...(goal
      ? [[result === 'goal' ? 100 : 0, 50] as [number, number]]
      : result === 'loose'
        ? [
            looseAt ??
              ([
                Math.max(5, Math.min(95, x + (player.startsWith('h-') ? 12 : -12))),
                Math.min(95, y + 8),
              ] as [number, number]),
          ]
        : []),
  ];
  return { ...action(
    label,
    feedback,
    art ??
      (result === 'goal'
        ? 'match-home-goal'
        : result === 'concede'
          ? 'match-rival-goal'
          : result === 'lost'
            ? 'match-interception'
            : result === 'regain'
              ? 'match-duel'
              : 'right-midfielder-3'),
    [...moves.filter((m) => m[0] !== player), contact],
    path,
    result,
    result === 'next' || result === 'goal' || result === 'regain'
      ? 'positive'
      : result === 'lost' || result === 'concede'
        ? 'negative'
        : 'neutral',
  ), ...(routes ? { routes } : {}) };
}
const best = (a: Action): Action => ({ ...a, tone: 'positive' });
