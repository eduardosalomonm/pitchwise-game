const p = (id: string, x: number, y: number): Placement => [id, x, y];

type Episode = {
  name: string;
  owner: string;
  positions: Placement[];
  turns: Turn[];
};
const e = (
  name: string,
  owner: string,
  positions: Placement[],
  ...turns: Turn[]
): Episode => ({ name, owner, positions, turns });

// New opponents are fictional scouting profiles of Rival XI, not licensed clubs.
function fixture(
  id: string,
  name: string,
  difficulty: 'Easy' | 'Intermediate' | 'Hard',
  opponent: string,
  description: string,
  cover: string,
  episodes: Episode[],
): MatchFixture {
  return {
    id,
    name,
    difficulty,
    opponent,
    description,
    cover: `/illustrations/actions/${cover}.webp`,
    moments: episodes.map((episode, index) => {
      const moment = advancedMoment(
        `${id}-${index + 1}`,
        [8, 26, 43, 66, 87][index],
        episode.name,
        `${opponent}: ${episode.name.toLowerCase()}.`,
        episode.owner,
        episode.positions,
        episode.turns,
      );
      for (const node of moment.nodes)
        for (const choice of node.choices)
          if (choice.outcome?.homeGoals)
            choice.outcome.headline = `GOAL — ${episode.name.toLowerCase()}!`;
      return moment;
    }),
  };
}

