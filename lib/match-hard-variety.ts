type Contact = [string, number, number];
const p = (id: string, x: number, y: number): Placement => [id, x, y];
const artwork: Record<string, string> = {
  'match-pass': 'right-midfielder-1',
  'match-heading': 'match-rival-header',
  'full-back-1': 'right-back-1',
  'full-back-2': 'right-back-2',
  'full-back-3': 'right-back-3',
  'full-back-4': 'right-back-4',
  'defensive-midfielder-1': 'right-midfielder-1',
  'defensive-midfielder-2': 'striker-4',
  'defensive-midfielder-3': 'right-midfielder-3',
  'defensive-midfielder-4': 'left-midfielder-4',
  'defensive-midfielder-5': 'left-midfielder-5',
};

// Contacts are authored in order. A cross, lay-off or interception keeps each
// intermediate touch in the animation instead of jumping straight to its result.
function a(
  label: string,
  feedback: string,
  result: Ending | 'next' | Turn,
  contacts: Contact[],
  moves: Placement[] = [],
  art = 'match-pass',
  positive = false,
): Action {
  const scoring = result === 'goal' || result === 'concede';
  const path: [number, number][] = contacts.map(([, x, y]) => [x, y]);
  if (scoring) path.push([result === 'goal' ? 100 : 0, 50]);
  const last = new Map<string, Placement>();
  for (const placement of [...moves, ...contacts])
    last.set(placement[0], placement);
  return action(
    label,
    feedback,
    scoring
      ? result === 'goal'
        ? 'match-home-goal'
        : 'match-rival-goal'
      : (artwork[art] ?? art),
    [...last.values()],
    path,
    result,
    positive || result === 'next' || result === 'goal'
      ? 'positive'
      : typeof result === 'object' || result === 'lost' || result === 'concede'
        ? 'negative'
        : 'neutral',
  );
}

type Episode = {
  name: string;
  owner: string;
  positions: Placement[];
  turns: Turn[];
};
const episode = (
  name: string,
  owner: string,
  positions: Placement[],
  ...turns: Turn[]
): Episode => ({ name, owner, positions, turns });
function fixture(
  id: string,
  name: string,
  opponent: string,
  description: string,
  cover: string,
  episodes: Episode[],
): MatchFixture {
  return {
    id,
    name,
    opponent,
    difficulty: 'Hard',
    description,
    cover: `/illustrations/actions/${artwork[cover] ?? cover}.webp`,
    moments: episodes.map((ep, index) => {
      const moment = advancedMoment(
        `${id}-${index + 1}`,
        [8, 26, 43, 66, 87][index],
        ep.name,
        `${opponent}: ${ep.name.toLowerCase()}.`,
        ep.owner,
        ep.positions,
        ep.turns,
      );
      for (const node of moment.nodes)
        for (const choice of node.choices) {
          if (choice.outcome?.homeGoals)
            choice.outcome.headline = `GOAL — ${ep.name.toLowerCase()}!`;
        }
      return moment;
    }),
  };
}

