function build(spec: Spec): RedCardPlay {
  const shape = spec.turns[0].phase === 'Attacking' ? attackShape : defendShape;
  const overrides = new Map(spec.placements.map((p) => [p[0], p]));
  const placements = shape.map((p) => overrides.get(p[0]) ?? p);
  for (const p of spec.placements)
    if (!shape.some((base) => base[0] === p[0])) placements.push(p);
  const absent = spec.team === 'home' ? 'h-l8' : 'a-l8';
  const moment = advancedMoment(
    spec.id,
    62,
    spec.name,
    spec.introduction,
    spec.owner,
    placements,
    spec.turns,
  );
  moment.nodes = moment.nodes.map((node) => ({
    ...node,
    scene: {
      ...node.scene,
      players: node.scene.players.filter((p) => p.id !== absent),
      unavailablePlayerIds: [absent],
    },
    choices: node.choices.map((choice) => ({
      ...choice,
      movement: choice.movement.filter((move) => move.playerId !== absent),
    })),
  }));
  return { team: spec.team, tier: spec.team === 'home' ? 2 : 0, moment };
}

